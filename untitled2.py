import os
import glob
import warnings
import numpy as np
import pandas as pd
from statsmodels.tsa.holtwinters import ExponentialSmoothing
from statsmodels.tsa.filters.hp_filter import hpfilter
from sklearn.metrics import mean_squared_error, mean_absolute_error, mean_absolute_percentage_error
import plotly.graph_objects as go
import plotly.express as px
from plotly.subplots import make_subplots
from google.colab import drive, files

warnings.filterwarnings('ignore')

# ==============================================================================
# 1. INGESTÃO E HIGIENIZAÇÃO DE DADOS (ETL)
# ==============================================================================
def carregar_dados(nome_arquivo='preco_cafe.csv'):
    try:
        drive.mount('/content/drive', force_remount=False)
    except Exception:
        pass

    caminhos = glob.glob(f'/content/drive/**/{nome_arquivo}', recursive=True)
    path = caminhos[0] if caminhos else None

    if not path:
        print(f"Arquivo '{nome_arquivo}' não localizado no Drive. Faça o upload:")
        uploaded = files.upload()
        path = next(iter(uploaded.keys()), None)

    if not path or not os.path.exists(path):
        raise FileNotFoundError("Base de dados não fornecida.")

    return pd.read_csv(path)

df_raw = carregar_dados()

meses_map = {
    'Jan': 1, 'Fev': 2, 'Mar': 3, 'Abr': 4, 'Mai': 5, 'Jun': 6,
    'Jul': 7, 'Ago': 8, 'Set': 9, 'Out': 10, 'Nov': 11, 'Dez': 12
}
cols_meses = [c for c in meses_map.keys() if c in df_raw.columns]

for col in cols_meses:
    df_raw[col] = (
        df_raw[col].astype(str)
        .str.replace(',', '.', regex=False)
        .astype(float)
    )

# Transformação para Série Temporal Mensal Real
df_ts = df_raw.melt(id_vars=['Ano'], value_vars=cols_meses, var_name='Mes_Nome', value_name='Preco')
df_ts['Mes'] = df_ts['Mes_Nome'].map(meses_map)
df_ts['Data'] = pd.to_datetime(dict(year=df_ts['Ano'], month=df_ts['Mes'], day=1))
df_ts = df_ts.dropna(subset=['Preco']).sort_values('Data').set_index('Data').asfreq('MS')

# ==============================================================================
# 2. MOTOR ANALÍTICO: FINANÇAS, MACROECONOMIA E ESTATÍSTICA
# ==============================================================================
serie = df_ts['Preco']
retornos = serie.pct_change().dropna()
log_retornos = np.log(serie / serie.shift(1)).dropna()

# A. Mercado Financeiro
n_anos = (serie.index[-1] - serie.index[0]).days / 365.25
cagr = ((serie.iloc[-1] / serie.iloc[0]) ** (1 / n_anos) - 1) * 100
vol_anual = log_retornos.std() * np.sqrt(12) * 100
sharpe_ratio = (cagr - 10.5) / vol_anual
rolling_max = serie.cummax()
drawdown_serie = ((serie - rolling_max) / rolling_max) * 100
var_95 = np.percentile(retornos, 5) * 100

metricas_financeiras = {
    'Preço Médio Histórico': f"R$ {serie.mean():.2f}",
    'CAGR (Crescimento Anual)': f"{cagr:.2f}%",
    'Volatilidade Anualizada': f"{vol_anual:.2f}%",
    'Índice de Sharpe (Rf=10.5%)': f"{sharpe_ratio:.2f}",
    'Drawdown Máximo': f"{drawdown_serie.min():.2f}%",
    'VaR Mensal (95%)': f"{var_95:.2f}%"
}

# B. Macroeconomia: Filtro HP e Elasticidade-Preço da Demanda
ciclo_hp, tendencia_hp = hpfilter(serie, lamb=14400)
df_ts['Tendencia_Macro_HP'] = tendencia_hp
df_ts['Hiato_Preco_%'] = (ciclo_hp / tendencia_hp) * 100

ELASTICIDADE_DEMANDA_CAFE = -0.25
var_preco_acumulada = ((serie.iloc[-1] / serie.iloc[0]) - 1) * 100
impacto_demanda_estimado = var_preco_acumulada * ELASTICIDADE_DEMANDA_CAFE

metricas_macro = {
    'Elasticidade-Preço (εd)': f"{ELASTICIDADE_DEMANDA_CAFE:.2f}",
    'Variação Acumulada Preço': f"{var_preco_acumulada:.2f}%",
    'Contração Implícita Demanda': f"{impacto_demanda_estimado:.2f}%",
    'Hiato Preço vs Tendência HP': f"{df_ts['Hiato_Preco_%'].iloc[-1]:.2f}%",
    'Inflação Média Mensal': f"{retornos.mean() * 100:.2f}%"
}

# ==============================================================================
# 3. MACHINE LEARNING: VALIDAÇÃO TEMPORAL E HOLT-WINTERS SAZONAL
# ==============================================================================
horizonte_teste = 12
treino, teste = serie.iloc[:-horizonte_teste], serie.iloc[-horizonte_teste:]

modelo_val = ExponentialSmoothing(
    treino, trend='add', seasonal='mul', seasonal_periods=12, damped_trend=True
).fit(optimized=True)
pred_teste = modelo_val.forecast(horizonte_teste)

rmse = np.sqrt(mean_squared_error(teste, pred_teste))
mae = mean_absolute_error(teste, pred_teste)
mape = mean_absolute_percentage_error(teste, pred_teste) * 100
mase = mae / np.mean(np.abs(np.diff(treino, n=12)))

metricas_ml = {
    'RMSE (Erro Quadrático)': f"R$ {rmse:.2f}",
    'MAE (Erro Absoluto)': f"R$ {mae:.2f}",
    'MAPE (Erro Percentual)': f"{mape:.2f}%",
    'MASE (< 1.0 bate Naive)': f"{mase:.3f}",
    'AIC (Critério Akaike)': f"{modelo_val.aic:.1f}"
}

# Modelo Final (Previsão 60 meses = 5 anos)
modelo_final = ExponentialSmoothing(
    serie, trend='add', seasonal='mul', seasonal_periods=12, damped_trend=True
).fit(optimized=True)

passos_futuros = 60
previsao_mensal = modelo_final.forecast(passos_futuros)
margem_erro_95 = 1.96 * modelo_final.resid.std() * np.sqrt(np.arange(1, passos_futuros + 1) / 12)

df_prev = pd.DataFrame({
    'Previsao_Preco': previsao_mensal,
    'IC_Inferior_95': previsao_mensal - margem_erro_95,
    'IC_Superior_95': previsao_mensal + margem_erro_95
})

# ==============================================================================
# 4. GRÁFICOS INTERATIVOS (PLOTLY)
# ==============================================================================
fig1 = go.Figure()
fig1.add_trace(go.Scatter(x=serie.index, y=serie, name='Preço Observado (R$)', line=dict(color='#1f77b4', width=2)))
fig1.add_trace(go.Scatter(x=df_ts.index, y=df_ts['Tendencia_Macro_HP'], name='Tendência Macro (Filtro HP)', line=dict(color='#2ca02c', dash='dot', width=2)))
fig1.add_trace(go.Scatter(x=df_prev.index, y=df_prev['Previsao_Preco'], name='Previsão Holt-Winters (5 Anos)', line=dict(color='#d62728', width=2.5)))
fig1.add_trace(go.Scatter(
    x=df_prev.index.tolist() + df_prev.index[::-1].tolist(),
    y=df_prev['IC_Superior_95'].tolist() + df_prev['IC_Inferior_95'][::-1].tolist(),
    fill='toself', fillcolor='rgba(214, 39, 40, 0.15)',
    line=dict(color='rgba(255,255,255,0)'), name='Intervalo de Confiança 95%'
))
fig1.update_layout(title='Evolução do Preço do Café, Tendência Macro e Projeção Holt-Winters', xaxis_title='Data', yaxis_title='Preço da Saca (R$)', template='plotly_white', hovermode='x unified', height=480)

fig2 = make_subplots(rows=2, cols=1, shared_xaxes=True, subplot_titles=('Retornos Mensais (%) e VaR 95%', 'Drawdown Histórico (% de Queda do Topo)'))
fig2.add_trace(go.Bar(x=retornos.index, y=retornos * 100, name='Retorno Mensal (%)', marker_color=np.where(retornos >= 0, '#2ca02c', '#d62728')), row=1, col=1)
fig2.add_hline(y=var_95, line_dash="dash", line_color="orange", annotation_text=f"VaR 95%: {var_95:.2f}%", row=1, col=1)
fig2.add_trace(go.Scatter(x=drawdown_serie.index, y=drawdown_serie, fill='tozeroy', name='Drawdown (%)', line=dict(color='#9467bd')), row=2, col=1)
fig2.update_layout(title='Análise de Risco e Volatilidade do Mercado de Café', template='plotly_white', height=550)

fig3 = px.box(df_ts, x='Mes_Nome', y='Preco', color='Mes_Nome', title='Distribuição Sazonal dos Preços por Mês (Safra vs. Entressafra)', labels={'Mes_Nome': 'Mês', 'Preco': 'Preço da Saca (R$)'}, template='plotly_white', height=450)
fig3.update_layout(showlegend=False)

